test('edição persiste nova revisão, aplicação e restauração usam o backend', async ({ page, request }) => {
  await page.goto('/')
  const app = page.frameLocator('iframe')
  await app.getByRole('button', { name: 'Abrir carteira' }).waitFor()
  await page.getByRole('button', { name: 'Revisar proposta de teste' }).click()
  await app.getByRole('button', { name: 'Revisar proposta', exact: true }).click()
  await app.getByText('Editar proposta', { exact: true }).click()
  await app.getByLabel('Repetições', { exact: false }).fill('12')
  await expect(app.getByRole('button', { name: 'Aplicar programa', exact: true })).toBeDisabled()
  await app.getByRole('button', { name: 'Salvar proposta' }).click()
  await expect(app.getByText(/Revisão da proposta 2/)).toBeVisible()
  await app.getByRole('button', { name: 'Aplicar programa', exact: true }).click()
  await expect(app.getByText(/Programa aplicado em/)).toBeVisible()
  expect((await (await request.get('/_test/status')).json()).revisao).toBe(1)
  await app.getByRole('button', { name: 'Restaurar programa anterior' }).click()
  await expect(app.getByText(/Programa restaurado em/)).toBeVisible()
  expect((await (await request.get('/_test/status')).json()).revisao).toBe(2)
})

