test('320 px, tema escuro e foco de teclado sem rolagem horizontal', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 700 })
  await page.goto('/?theme=dark')
  const app = page.frameLocator('iframe')
  await app.getByRole('button', { name: 'Abrir carteira' }).click()
  await expect(app.locator('main')).toHaveAttribute('data-theme', 'dark')
  const frame = page.frames().find(f => f.url().includes('/_test/ui'))!
  expect(await frame.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await app.getByRole('textbox', { name: 'Buscar aluno' }).focus()
  await page.keyboard.press('Tab')
  await expect(app.getByLabel('Mostrar', { exact: true })).toBeFocused()
})

