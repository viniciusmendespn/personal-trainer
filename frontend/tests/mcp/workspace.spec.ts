test('evolução consulta o ID exportado e separa unidades do histórico', async ({ page, request }) => {
  const browserErrors: string[] = []
  page.on('pageerror', error => browserErrors.push(error.message))
  await page.goto('/')
  const app = page.frameLocator('iframe')
  await app.getByRole('button', { name: 'Abrir carteira' }).waitFor()
  await page.getByRole('button', { name: 'Revisar proposta de teste' }).click()
  await app.getByRole('button', { name: 'Revisar proposta', exact: true }).click()
  await app.getByRole('button', { name: 'Aplicar programa', exact: true }).click()
  await expect(app.getByText(/Programa aplicado em/)).toBeVisible()
  await request.post('/_test/evolution')
  await app.getByRole('button', { name: 'Ver programa', exact: true }).click()
  await app.getByRole('button', { name: 'Evolução', exact: true }).click()
  await expect(app.getByLabel('Unidade', { exact: true })).toHaveValue('kg')
  await expect(app.getByRole('cell', { name: '20', exact: true })).toBeVisible()
  await expect(app.getByRole('img', { name: /Evolução em kg/ })).toBeVisible()
  await app.getByLabel('Unidade', { exact: true }).selectOption('lb')
  await expect(app.getByRole('cell', { name: '40', exact: true })).toBeVisible()
  await expect(app.getByRole('cell', { name: '20', exact: true })).toHaveCount(0)
  await app.getByLabel('Unidade', { exact: true }).selectOption('unidade não informada')
  await expect(app.getByRole('cell', { name: '10', exact: true })).toBeVisible()
  await expect(app.locator('svg[role="img"]')).toHaveCount(0)
  expect(browserErrors).toEqual([])
})
